"""
VRSBench Scene Captioning Evaluation Script.
Evaluates model-generated captions against reference annotations.
Strict compliance: Never generates fabricated scores when dataset is missing.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime
from pathlib import Path

# Add project root
sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))

from training.datasets.vrsbench import VRSBenchAdapter
from evaluation.vrsbench.metrics import compute_bleu4, compute_rouge_l


def evaluate_captioning(
    dataset_path: str = "data/vrsbench",
    split: str = "test",
    model_name: str = "satquery-vlm-v1",
    model_version: str = "1.0.0"
) -> dict:
    adapter = VRSBenchAdapter(dataset_path)

    if not adapter.is_available():
        report = {
            "dataset": "VRSBench",
            "task": "captioning",
            "split": split,
            "status": "dataset_not_available",
            "message": f"VRSBench dataset not found at '{dataset_path}'. Download the benchmark files to run evaluation.",
            "metrics": None
        }
        return report

    samples = adapter.load_caption_samples(split)
    if not samples:
        return {
            "dataset": "VRSBench",
            "task": "captioning",
            "split": split,
            "status": "dataset_empty_or_invalid",
            "message": f"No caption annotations found in '{dataset_path}'.",
            "metrics": None
        }

    # Evaluate genuine samples
    total_bleu = 0.0
    total_rouge = 0.0
    evaluated_count = 0

    for item in samples:
        ref = item.get("caption") or item.get("reference", "")
        # Real inference prediction from model or pre-computed field
        pred = item.get("prediction", "")
        if ref and pred:
            total_bleu += compute_bleu4(ref, pred)
            total_rouge += compute_rouge_l(ref, pred)
            evaluated_count += 1

    if evaluated_count == 0:
        return {
            "dataset": "VRSBench",
            "task": "captioning",
            "split": split,
            "status": "pending_predictions",
            "message": f"Loaded {len(samples)} references. Predictions need to be generated by model before scoring.",
            "sample_count": len(samples),
            "metrics": None
        }

    metrics = {
        "bleu_4": round(total_bleu / evaluated_count, 2),
        "rouge_l": round(total_rouge / evaluated_count, 2),
        "samples_evaluated": evaluated_count
    }

    timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
    result = {
        "dataset": "VRSBench",
        "dataset_version": "1.0.0",
        "split": split,
        "task": "captioning",
        "model": model_name,
        "model_version": model_version,
        "timestamp": datetime.utcnow().isoformat() + "Z",
        "metrics": metrics,
        "sample_count": evaluated_count,
        "status": "COMPLETED"
    }

    # Save to evaluation/results
    results_dir = Path("evaluation/results")
    results_dir.mkdir(parents=True, exist_ok=True)
    out_file = results_dir / f"vrsbench_caption_{timestamp}.json"
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2)

    return result


def main():
    parser = argparse.ArgumentParser(description="Run VRSBench Captioning Evaluation")
    parser.add_argument("--data_dir", type=str, default="data/vrsbench")
    parser.add_argument("--split", type=str, default="test")
    args = parser.parse_args()

    res = evaluate_captioning(args.data_dir, args.split)
    print(json.dumps(res, indent=2))


if __name__ == "__main__":
    main()
